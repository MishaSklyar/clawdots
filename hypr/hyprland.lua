bind("ALT + Tab", function() alt_held = true; hl.exec_cmd(qs .. " ipc call switcher next") end)
bind("ALT + SHIFT + Tab", function() alt_held = true; hl.exec_cmd(qs .. " ipc call switcher prev") end)
