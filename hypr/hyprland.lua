-- focus / move / resize: arrows or hjkl
local resize_step = 40
local dirs = {
	{ "left", "l", "left", -resize_step, 0 }, { "H", "l", "left", -resize_step, 0 },
	{ "right", "r", "right", resize_step, 0 }, { "L", "r", "right", resize_step, 0 },
	{ "up", "u", "up", 0, -resize_step }, { "K", "u", "up", 0, -resize_step },
	{ "down", "d", "down", 0, resize_step }, { "J", "d", "down", 0, resize_step },
}
for _, d in ipairs(dirs) do
	local key, short, long, rx, ry = d[1], d[2], d[3], d[4], d[5]
	bind(mod .. " + " .. key, hl.dsp.focus({ direction = short }))
	bind(mod .. " + SHIFT + " .. key, hl.dsp.window.move({ direction = long }))
	bind(mod .. " + CTRL + " .. key, hl.dsp.window.resize({ x = rx, y = ry, relative = true }), { repeating = true })
end

