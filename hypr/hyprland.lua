-- claude hot corner: hold SUPER and push the mouse into the bottom-right corner
-- (opens claude.ai / claude code in wezterm / the Claude app; see quickshell/Corner.qml)
local corner_armed = true
hl.timer(function()
	local p, m = hl.get_cursor_pos(), hl.get_monitor_at_cursor()
	if not p or not m then return end
	local s = m.scale or 1
	local in_corner = p.x >= m.x + m.width / s - 3 and p.y >= m.y + m.height / s - 3
	if not in_corner then
		corner_armed = true
	elseif corner_armed and (hl.is_key_down("Super_L") or hl.is_key_down("Super_R")) then
		corner_armed = false
		hl.exec_cmd(qs .. " ipc call popup open corner")
	end
end, { timeout = 50, type = "repeat" })

